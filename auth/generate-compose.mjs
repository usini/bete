import { readFileSync, writeFileSync } from 'node:fs';
const code = readFileSync(new URL('./server.mjs', import.meta.url), 'utf8');
// A data URL avoids config mounts and shell interpolation in Portainer.
const launch = `import('data:text/javascript;base64,${Buffer.from(code).toString('base64')}').then(m=>m.createAuthServer().listen(3000,'0.0.0.0',()=>console.log('Bete OAuth listening')))`;
writeFileSync(new URL('./compose.portainer.yml', import.meta.url), `# Generated by node auth/generate-compose.mjs. Docker Standalone / Portainer; no config mounts required.
services:
  bete-auth:
    image: node:24-alpine
    restart: unless-stopped
    user: node
    init: true
    read_only: true
    cap_drop: [ALL]
    security_opt: [no-new-privileges:true]
    command:
      - node
      - --input-type=module
      - -e
      - ${JSON.stringify(launch)}
    environment:
      APP_ORIGIN: https://bete.usini.eu
      PUBLIC_URL: https://auth-bete.usini.eu
      GOOGLE_CLIENT_ID: \${GOOGLE_CLIENT_ID:?Set GOOGLE_CLIENT_ID in Portainer}
      GOOGLE_CLIENT_SECRET: \${GOOGLE_CLIENT_SECRET:?Set GOOGLE_CLIENT_SECRET in Portainer}
      COOKIE_KEY: \${COOKIE_KEY:?Set COOKIE_KEY in Portainer}
    # Change HOST_PORT in Portainer; the container always listens on 3000.
    ports:
      - "\${BIND_ADDRESS:-127.0.0.1}:\${HOST_PORT:-3100}:3000"
    healthcheck:
      test: [CMD, node, -e, "fetch('http://127.0.0.1:3000/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 30s
      timeout: 5s
      retries: 3
    logging:
      driver: local
      options:
        max-size: 5m
        max-file: "2"
`);

